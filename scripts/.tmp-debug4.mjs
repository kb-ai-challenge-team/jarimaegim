import { chromium } from "playwright-core";
const base = "http://127.0.0.1:4173";
const browser = await chromium.launch({ headless: true, executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
page.on("console", m => console.log("console:", m.type(), m.text().slice(0,250)));
page.on("pageerror", e => console.log("PAGEERROR:", e.message.slice(0,500)));
page.on("response", r => { if (r.status() >= 400) console.log("BAD:", r.status(), r.url().replace(base,""), r.headers()["content-type"]); });
page.on("requestfailed", r => console.log("FAILED:", r.url().replace(base,""), r.failure()?.errorText));
await page.goto(`${base}/start`, { waitUntil: "networkidle" });
await page.waitForTimeout(3000);
console.log("start page hydrated:", await page.evaluate(() => Object.keys(document.querySelector("main")||{}).some(k=>k.startsWith("__react"))));
await browser.close();
