import { chromium } from "playwright-core";
const base = "http://127.0.0.1:4173";
const browser = await chromium.launch({ headless: true, executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
page.on("console", m => console.log("console:", m.type(), m.text().slice(0,200)));
page.on("pageerror", e => console.log("pageerror:", e.message.slice(0,300)));
page.on("requestfinished", async r => { if (r.url().includes("/api/v1")) { const res = await r.response(); console.log("net:", res.status(), r.method(), r.url().replace(base,"")); } });
page.on("requestfailed", r => { if (r.url().includes("/api/v1")) console.log("netfail:", r.method(), r.url().replace(base,""), r.failure()?.errorText); });
await context.request.post(base + "/api/v1/sessions/anonymous", { data: { retention_notice_accepted: true } });
const created = await context.request.post(base + "/api/v1/cases", { data: { title: "t", inputs: { industry: "카페", district: "마포구", budget_krw: 100000000, equity_krw: 70000000, business_stage: "PRE_OPEN", startup_type: "INDEPENDENT", priority: "STABILITY" } } });
const record = await created.json();
console.log("cookies", (await context.cookies()).map(c=>c.name+"="+c.value.slice(0,6)).join(","));
await page.goto(`${base}/cases/${record.id}/explore`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(12000);
console.log("body:", (await page.locator("body").innerText()).slice(0, 300));
await browser.close();
