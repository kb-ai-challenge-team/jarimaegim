import { chromium } from "playwright-core";
const base = "http://127.0.0.1:4173";
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_BIN });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
page.on("pageerror", e => console.log("PAGEERROR:", e.message.slice(0,600)));
page.on("request", r => { if (r.url().includes("/api/v1")) console.log("req:", r.method(), r.url().replace(base,"")); });
await page.goto(`${base}/privacy`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.getByRole("button", { name: /삭제 요청 번호 발급/ }).click().catch(e => console.log("clickfail", e.message.slice(0,120)));
await page.waitForTimeout(2500);
console.log("status text:", await page.locator("[role=status]").textContent().catch(()=> "none"));
await browser.close();
