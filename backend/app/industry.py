_NORMALISE = re.compile(r"[\s\-_/()·]+")


def normalise(text: str) -> str:
    """비교용 정규화. 공백·하이픈·괄호를 지우고 소문자로 맞춘다."""
    return _NORMALISE.sub("", (text or "").strip().lower())


def resolve(industry: str) -> str | None:
    """업종 문자열을 서비스업종 코드로 바꾼다. 확실하지 않으면 None.

    별칭 표에 정확히 있는 것만 인정한다. 부분 문자열 매칭은 하지 않는다 —
    '스터디카페'가 '카페'를 포함한다고 커피전문점 상권 수치를 붙이면 안 되기 때문이다.
    """
    key = normalise(industry)
    if not key:
        return None
    if key.upper() in INDUSTRY_NAMES:
        return key.upper()
    return _ALIASES.get(key)


# 업종 뒤에 붙어 들어오는 조사. 긴 것을 먼저 봐야 '에서' 가 '에' 로 잘리지 않는다.
_PARTICLES = ("이라고", "라고", "이랑", "에게", "에서", "으로", "까지", "부터",
              "을", "를", "은", "는", "이", "가", "과", "와", "랑", "의", "도", "만", "에", "로")


def canonical(industry: str) -> str:
    """조사가 붙어 들어온 업종을 별칭 표에 있는 형태로 되돌린다.

    모델은 "카페를 준비 중"에서 업종을 `카페를` 로 뽑는다. 인용은 사용자의 말 그대로여야 하니
    그 자체는 옳지만, `카페를` 은 표에 없어 상권 코드로 풀리지 않고 후보가 근거 B 대신 근거 C 로
    떨어진다 — 조사 한 글자가 핵심 판정을 조용히 지운다.

    **이미 풀리는 값은 손대지 않는다.** 그래서 이 함수가 할 수 있는 일은 못 찾던 것을 찾게
    만드는 것뿐이고, 찾던 것을 다른 업종으로 옮기지는 못한다. resolve 의 "표에 정확히 적힌
    것만" 규칙은 그대로 남는다 — 줄기가 표에 없으면(`스터디카페를`) 그대로 돌려보낸다.
    """
    text = (industry or "").strip()
    if not text or resolve(text):
        return text
    for particle in _PARTICLES:
        if not text.endswith(particle):
            continue
        stem = text[: -len(particle)].strip()
        if stem and resolve(stem):
            return stem
    return text


def display_name(code: str) -> str:
    return INDUSTRY_NAMES.get(code, code)


#: 되묻기에 함께 보여줄 후보 수. 목록이 길면 사용자가 고르지 않고 아무거나 누른다.
SUGGESTION_LIMIT = 6

#: 겹치는 별칭이 없을 때 보여줄 대표 업종. 빈 목록은 "고칠 방법이 없다"로 읽힌다.
_FALLBACK_SUGGESTIONS = ("카페", "한식", "치킨", "미용실", "편의점", "학원")


def suggest(industry: str) -> list[str]:
    """정규화에 실패한 입력에 대해 **표시용** 후보를 고른다. 매칭이 아니다.

    `resolve()` 가 부분 문자열 매칭을 하지 않는 이유와 이 함수가 존재하는 이유는 같다 —
    '스터디카페'를 '카페'로 **자동으로 붙이면** 전혀 다른 업종의 원가율과 폐업률이 그 사람의
    판단 근거가 된다. 그래서 여기서는 고를 수 있는 것을 보여 주기만 하고, 무엇이 선택되는지는
    사용자가 정한다. 이 반환값이 조건에 자동으로 들어가는 경로는 없다.
    """
    key = normalise(industry)
    if not key:
        return []
    near = [alias for alias in _ALIASES if alias in key or key in alias]
    ordered = near + [item for item in _FALLBACK_SUGGESTIONS if item not in near]
    return ordered[:SUGGESTION_LIMIT]
